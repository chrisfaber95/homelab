-- Baseline (H-023 B4): the nine tables of today's SQLite inbox.db, as the Python inbox creates them
-- (bin/homelab_inbox/{storage,conversation,chat}.py), with the ALTER TABLE history of storage.py collapsed into
-- the CREATE TABLE statements. Same table and column names, same column order.
-- Types: SQLite TEXT -> text (times stay ISO-8601 strings, as in the old database), INTEGER -> integer,
-- REAL -> double precision. The SQLite "INTEGER PRIMARY KEY" / AUTOINCREMENT ids become identity columns
-- (BY DEFAULT, so the one-off import can load the old ids; B5 must then reset each sequence).
-- SQLite has no secondary indexes here, so there are none: only the primary keys.
-- NEVER EDIT THIS FILE after it has been merged: every later schema change is a new V<n>__*.sql migration.

CREATE TABLE tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo text NOT NULL,
    text text NOT NULL,
    status text NOT NULL,
    created text NOT NULL,
    started text,
    ended text,
    session text NOT NULL,
    rounds integer DEFAULT 0,
    pending_input text,
    question text,
    answer text,
    summary text,
    pr_number integer,
    pr_url text,
    last_comment_at text,
    turns integer DEFAULT 0,
    note text,
    job text,
    run_id integer,
    mem_source text,
    mem_link text,
    remembered integer DEFAULT 0,
    model text,
    reprepare integer DEFAULT 0,
    parent integer,
    after_task integer,
    reason text,
    brief text,
    criteria text,
    reviews integer DEFAULT 0,
    review text,
    handoff text,
    unattended integer DEFAULT 0,
    review_ok integer,
    conflicts integer DEFAULT 0,
    conflict_sha text,
    restarts integer DEFAULT 0,
    accepted integer DEFAULT 0,
    no_auto_revive integer DEFAULT 0,
    source text
);

CREATE TABLE job_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job text NOT NULL,
    kind text,
    model text,
    due text,
    created text NOT NULL,
    started text,
    ended text,
    dispatched text,
    status text NOT NULL,
    summary text,
    note text,
    task_id integer,
    manual integer DEFAULT 0,
    minutes integer,
    mode text,
    deliver text,
    source text
);

CREATE TABLE job_state (
    name text PRIMARY KEY,
    last_due text NOT NULL
);

CREATE TABLE drafts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created text NOT NULL,
    request text NOT NULL,
    base text,
    status text NOT NULL,
    text text,
    error text
);

CREATE TABLE skill_prs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    task_id integer,
    pr_url text,
    created text NOT NULL
);

CREATE TABLE kv (
    key text PRIMARY KEY,
    value text
);

CREATE TABLE conversation (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time text NOT NULL,
    author text NOT NULL,
    client text NOT NULL,
    kind text NOT NULL,
    text text NOT NULL,
    link text,
    ref text
);

CREATE TABLE conversation_refusals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time text NOT NULL,
    client text NOT NULL,
    action text NOT NULL,
    why text NOT NULL
);

CREATE TABLE approvals (
    token text PRIMARY KEY,
    client text NOT NULL,
    brief text NOT NULL,
    mode text NOT NULL,
    created text NOT NULL,
    expires double precision NOT NULL,
    status text NOT NULL,
    task_id integer
);
